package setops

// Intersect возвращает элементы a, которые встречаются в b.
//
// Повторы в результате отсутствуют: каждый элемент встречается не более
// одного раза. Порядок результата — порядок первых вхождений
// соответствующих элементов в a; порядок b на результат не влияет.
// Ни a, ни b не изменяются. Пустая строка — обычный элемент наравне
// с остальными.
//
// Если a равен nil, результат nil. Если a не nil, результат не nil,
// даже если ни один элемент a не входит в b. b, равный nil, означает
// пустое множество.
func Intersect(a, b []string) []string {
	if a == nil {
		return nil
	}

	res := make([]string, 0)

	mp := make(map[string]struct{})

	for _, val := range a {
		mp[val] = struct{}{}
	}

	for _, val := range b {
		_, ok := mp[val]
		if ok {
			res = append(res, val)
		}
	}

	return res
}

// Difference возвращает элементы a, которых нет в b.
//
// Повторы в результате отсутствуют: каждый элемент встречается не более
// одного раза. Порядок результата — порядок первых вхождений
// соответствующих элементов в a; порядок b на результат не влияет.
// Ни a, ни b не изменяются. Пустая строка — обычный элемент наравне
// с остальными.
//
// Если a равен nil, результат nil. Если a не nil, результат не nil,
// даже если в нём нет элементов. b, равный nil, означает пустое
// множество.
func Difference(a, b []string) []string {
	if a == nil {
		return nil
	}

	res := make([]string, 0)

	mp := make(map[string]struct{})

	for _, val := range a {
		mp[val] = struct{}{}
	}

	for _, val := range b {
		_, ok := mp[val]
		if !ok {
			res = append(res, val)
		}
	}

	return res
}
