// Map строит глубокую копию дерева root той же формы, заменяя значение
// каждого узла результатом вызова transform.
//
// Пример: для дерева
//
//	  1
//	 / \
//	2   3
//	   /
//	  4
//
// и transform, умножающего значение на 10, результат должен быть
//
//	  10
//	 /  \
//	20   30
//	    /
//	  40
//
// Контракт:
//
//   - при успешном обходе transform вызывается ровно один раз для каждого
//     узла в порядке root → left → right; при ошибке вызывается только
//     соответствующий префикс этого порядка, включая сбойный узел;
//   - узлы результата должны быть новыми: менять или переиспользовать узлы
//     исходного дерева нельзя;
//   - для nil-дерева Map возвращает (nil, nil), ненулевой transform при
//     этом не вызывается;
//   - nil вместо transform — это ошибка ErrNilTransform, даже если дерево
//     пустое;
//   - ошибка transform оборачивается через %w; контекст должен содержать
//     исходное значение сбойного узла, а исходную ошибку должно быть
//     возможно найти через errors.Is;
//   - после первой ошибки обход прекращается, частичный результат наружу
//     не возвращается — первый результат должен быть nil.
//
// Порядок обхода — часть контракта, а не деталь реализации: transform
// может быть замыканием с состоянием (например, накапливать значения или
// вести счётчик), и перестановка вызовов относительно друг друга изменит
// наблюдаемое поведение вызывающего кода, даже если итоговое дерево при
// этом не изменится.
