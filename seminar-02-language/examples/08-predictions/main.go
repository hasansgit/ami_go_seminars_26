// Два прогноза: сначала назовите ответ, потом запускайте.
//
// Запуск:
//
//	go run ./seminar-02-language/examples/08-predictions
//
// Оба фрагмента выглядят так, будто ответ очевиден. Оба раза очевидный
// ответ неверный. Смысл упражнения — поймать себя на неверной интуиции
// до того, как она обойдётся в час отладки.
package main

import "fmt"

func main() {
	fmt.Println("=== Прогноз 1: затенение переменной ===")
	fmt.Println("result:", finalPrice(1200))

	fmt.Println()
	fmt.Println("=== Прогноз 2: адреса range-переменных ===")
	savedAddresses()
}

// finalPrice выглядит так, будто применяет скидку. Она её не применяет.
//
// Внутри if стоит `price := price - 100` — это не присваивание, а ОБЪЯВЛЕНИЕ
// новой переменной, которая живёт только внутри блока if и затеняет параметр.
// Наружная price не меняется, поэтому return отдаёт исходные 1200.
//
// Как заметить: `:=` создаёт новое имя, `=` меняет существующее.
// Как поймать заранее: go vet -vettool=shadow и линтеры ругаются на такое.
func finalPrice(price int) int {
	if price > 1000 {
		price := price - 100
		fmt.Println("inside:", price)
	}
	return price
}

// savedAddresses сохраняет адреса переменной цикла, а потом меняет исходный
// слайс. Вопрос: что напечатается?
//
// Ответ (начиная с Go 1.22) — 10 20 30.
//
// Две причины сразу:
//  1. На каждой итерации `for _, value := range` создаётся НОВАЯ переменная
//     value, поэтому три сохранённых адреса разные. До Go 1.22 переменная
//     была одна на весь цикл, и получилось бы 30 30 30 — этот код был
//     классическим источником багов.
//  2. value — это КОПИЯ элемента слайса, а не ссылка на него. Поэтому
//     values[0] = 99 на сохранённые адреса не влияет вообще.
func savedAddresses() {
	values := []int{10, 20, 30}
	var saved []*int

	for _, value := range values {
		saved = append(saved, &value)
	}

	values[0] = 99

	fmt.Println(*saved[0], *saved[1], *saved[2])

	// Адреса действительно разные — вот доказательство второй причины.
	fmt.Println("три разных адреса:", saved[0] != saved[1] && saved[1] != saved[2])

	// А чтобы получить ссылку именно на элемент слайса, берут адрес элемента,
	// а не переменной цикла:
	byIndex := &values[0]
	fmt.Println("&values[0] видит новое значение:", *byIndex)
}
