// Методы: объявление, получатель по значению и по указателю.
//
//	go run ./seminar-04-interfaces/examples/01-methods
package main

import "fmt"

// Counter — счётчик с двумя методами: один читает состояние, другой меняет.
type Counter struct {
	n int
}

// Value — получатель по ЗНАЧЕНИЮ: метод получает копию Counter.
// Состояние читать можно, менять бессмысленно — изменения останутся в копии.
func (c Counter) Value() int {
	return c.n
}

// Inc — получатель по УКАЗАТЕЛЮ: метод работает с оригиналом.
func (c *Counter) Inc() {
	c.n++
}

// Что выбрать? По умолчанию — указатель: методы меняют состояние чаще,
// чем кажется, копия большой структуры стоит дорого, а смешивать
// получателей в одном типе не принято. Значение — для маленьких
// неизменяемых типов вроде time.Time или Money из задачи 1.

func main() {
	c := Counter{}

	// Компилятор сам берёт адрес: c.Inc() — это (&c).Inc().
	// Такое возможно, только потому что c — адресуемая переменная.
	c.Inc()
	c.Inc()
	fmt.Println("после двух Inc:", c.Value()) // 2

	// Указатель тоже умеет вызывать методы с получателем по значению —
	// компилятор разыменует: p.Value() — это (*p).Value().
	p := &c
	p.Inc()
	fmt.Println("через указатель:", p.Value()) // 3

	// А вот Counter{ }.Inc() не скомпилируется: временное значение
	// не адресуемо, взять у него адрес нельзя. Раскомментируйте и
	// убедитесь:
	//
	// Counter{}.Inc()
}
