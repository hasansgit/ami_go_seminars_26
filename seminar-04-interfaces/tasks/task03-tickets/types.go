package tickets

// Ticket — заявка в службу поддержки.
//
// Priority — приоритет, меньшее значение означает более срочную заявку.
// Arrived — порядковый номер поступления, у всех заявок разный.
// ID — уникальный идентификатор заявки.
type Ticket struct {
	ID       int
	Priority int
	Arrived  int
}

// ByUrgency — слайс заявок, сортируемый по срочности.
//
// Порядок: сначала по возрастанию Priority, при равном приоритете — по
// возрастанию Arrived (кто раньше пришёл, тот раньше обслужен).
type ByUrgency []Ticket
